def pathway(doc):
    heading(doc, "4 What the conditioning pathway does, and does not do")
    para(doc, "Sections 3.2 and 3.6 establish that SST conditioning does not add skill "
              "here. A separate question is whether the pathway works as designed at all, "
              "because a mechanism that silently fails to transmit its input would call for "
              "a different remedy than one that transmits it faithfully to no effect. This "
              "section answers that question and, in doing so, addresses the reviewer "
              "request for negative controls on the interpretability diagnostics. Its "
              "conclusion is a caution rather than a claim: the pathway does work, and it "
              "does not help.")

    heading(doc, "4.1 Modulation parameters encode the SST state", 2)
    para(doc, "During evaluation the layer-wise scale and offset parameters generated by "
              "the index encoder were recorded over the historical record, and channel-wise "
              "Pearson correlations were computed between each encoder channel's parameter "
              "time series and the five standardised SST PCs, alongside two-dimensional "
              "principal-component projections of the deepest-layer modulation vectors.")
    figure(doc, "Fig10_FiLM_parameter_PCA.png",
           "Figure 10. (a) Projection of the fifth-encoder-layer scaling parameter, "
           "coloured by SST PC1; (b) the same for the shifting parameter. Colour denotes "
           "the phase of PC1, warm for El Nino-like and cool for La Nina-like states.")
    para(doc, "Both parameter sets are organised along the ENSO axis. Because they are "
              "produced by a deterministic multilayer perceptron from the SST scores, such "
              "structure is a consequence of the architecture rather than independent "
              "evidence that teleconnection physics has been learned. It shows that the "
              "index encoder propagates large-scale SST phase information without "
              "collapsing it, which is a necessary condition for conditional modulation and "
              "not a sufficient one for skill.")

    heading(doc, "4.2 The alignment exceeds a shuffled-PC control", 2)
    figure(doc, "Fig11_parameter_PC_correlation.png",
           "Figure 11. (a) Channel-wise correlations between the first-layer scaling "
           "parameter and the five SST PCs; (b) the same for the shifting parameter; (c) "
           "mean absolute correlation of the scaling parameter per PC with a 100-permutation "
           "shuffled-PC control and its 95th percentile; (d) the same for the shifting "
           "parameter. The control quantifies the correlation strength expected when the "
           "PC-parameter alignment is destroyed.")
    para(doc, "Channel-averaged mean absolute correlations for the scaling parameter are "
              "0.410, 0.334, 0.420, 0.259 and 0.239 for PC1 to PC5, against a shuffled-PC "
              "noise ceiling with 95th percentile at or below 0.072 and shuffled means of "
              "0.044 to 0.045. For the shifting parameter they are 0.446, 0.429, 0.291, "
              "0.343 and 0.207, likewise above a ceiling at or below 0.081. The alignment "
              "is therefore not an artifact of marginal distributions or of the capacity of "
              "the conditioning network, which was the specific concern raised in review. "
              "Correlation strength is non-monotonic across PC order, so the encoder "
              "distributes conditioning weight across the leading modes rather than relying "
              "on PC1 alone.")

    heading(doc, "4.3 The modulation it applies is small", 2)
    para(doc, "Measured on the trained models, the mean absolute scaling coefficient is "
              f"{MODULATION_MIN:.2f} to {MODULATION_MAX:.2f} per encoder level and the mean "
              "absolute offset is of the same order. The conditioning branch therefore "
              "perturbs each feature channel by a few percent. This is consistent with both "
              "preceding subsections and with Section 3.2: the pathway transmits a real "
              "signal, applies a small adjustment with it, and that adjustment does not "
              "improve, and slightly degrades, monthly pattern skill.")
    figure(doc, "Fig12_teleconnection_sensitivity.png",
           "Figure 12. Layer-wise global FiLM-EOF sensitivity maps for encoder layers 1 to 5 "
           "and the 100-permutation shuffled-PC control. All panels share one normalisation "
           "relative to the cross-layer peak.")
    para(doc, "Reconstructed sensitivity maps place the strongest layer-1 response over the "
              "equatorial eastern Pacific, consistent with the cold-tongue loading of PC1, "
              "with broader and more fragmented structure at depth. The shuffled-PC control "
              "remains near zero everywhere. These maps are linear weighted sums of five "
              "truncated global EOF modes and are reported as statistical sensitivity, not "
              "as evidence of direct causal oceanic forcing; extratropical maxima in "
              "particular reflect projection weights onto the EOF basis.")
    para(doc, "Taken together, these diagnostics make a methodological point that we "
              "consider the most transferable result of this study. Each of them is of the "
              "kind routinely offered as evidence that a conditioning mechanism has learned "
              "physically meaningful structure: a clean low-dimensional organisation along "
              "the ENSO axis, channel correlations far above a permutation control, and "
              "sensitivity maps centred on the canonical ENSO region. All three hold here. "
              "None of them implies skill, and in this case the skill is slightly negative. "
              "A persuasive interpretability analysis can belong to a component that does "
              "not help, so interpretability evidence and verification evidence should be "
              "reported together and neither should be read as a substitute for the other.")


def discussion(doc):
    stats = GAP["mean_test"]
    heading(doc, "5 Discussion")
    heading(doc, "5.1 Synthesis", 2)
    para(doc, "With training-period preprocessing and a physically reconstructed SEAS5 "
              "comparator, the three U-Net postprocessors differ far less than the first "
              "version of this study reported. Repeated training places the "
              "FiLM-minus-baseline ACC difference at "
              f"{f(stats['mean'], 4)} with a standard error of {f(stats['sem'], 4)}: a real "
              "but small cost to SST conditioning. The same measurement shows that this "
              "difference sits below what one training run can resolve, which is how the "
              "earlier conflicting rankings in this project arose.")
    para(doc, "The most direct empirical explanation for the modest value of SST "
              "conditioning is that the local precipitation field carries most of the "
              "information the network uses. Its permutation effect is more than an order "
              "of magnitude larger than any individual circulation channel, and removing or "
              "temporally mismatching the SST scores does not reduce FiLM spatial ACC. The "
              "six-month SST mean may suppress evolution and seasonal timing relevant to "
              "some regional rainfall signals: Liang et al. (2023) emphasise "
              "winter-to-spring SST changes for North China, while Yuan et al. (2019) "
              "distinguish early- from late-season teleconnections in South China. Those "
              "studies motivate alternative SST representations but do not establish the "
              "cause of the present ranking. A single five-score vector also cannot encode "
              "location-specific teleconnections, and the training set contains 285 monthly "
              "maps but far fewer independent climate regimes, so five-level conditional "
              "scaling may be difficult to estimate robustly.")
    para(doc, "Two measurement issues proved as consequential as the model comparison "
              "itself. Extreme-event CSI at a fixed threshold is dominated by output "
              "sharpness when forecasts are underdispersive, and equalising amplitude "
              "reverses the published ranking. Paired bootstrap intervals computed around "
              "one fixed set of trained models exclude training variability and are "
              "therefore narrower than they appear. Both are general properties of the "
              "verification setup rather than peculiarities of these models, and both would "
              "affect any comparison of this kind.")
    para(doc, "The corrected raw SEAS5 comparator also changes the interpretation. Bilinear "
              "remapping with a nonnegative precipitation constraint yields "
              f"{f(TEST['seas5']['mean_acc'])} exploratory ACC. Nonnegative bicubic "
              "remapping gives 0.288, and the previously reported 0.281 came from a "
              "standardised neural input rather than original model precipitation "
              "(Supplementary Figure S1). The visual and statistical comparison must use "
              "the same explicitly stated physical reconstruction; interpolation "
              "sensitivity is a limitation rather than evidence for a desired ranking.")

    heading(doc, "5.2 Limitations and future perspectives", 2)
    para(doc, "We group the limitations by whether they were measured in this study, "
              "inherited from its design and data, or left open.")
    para(doc, "Measured limitations. (1) Resolution of a single run: retraining an identical "
              f"configuration five times moves ensemble ACC by up to {f(FLOOR_ACC, 4)}. "
              "Every model difference reported here is smaller than that, so no single-run "
              "comparison, including those in earlier versions of this work, can establish "
              "a ranking; we report the mean and standard error over five retrainings "
              "instead. (2) Seed choice is the larger component: the decomposition gives a "
              f"nondeterminism standard deviation of "
              f"{f(FLOOR['variance_sources']['sd_across_runs_same_seed'], 4)} and a seed "
              f"component of {f(FLOOR['variance_sources']['sd_seed_component'], 4)}, so a "
              f"three-member ensemble on different seeds would move the gap by about "
              f"{f(RESEED, 4)}; one of our seeds produced a positive gap in two of five "
              "repetitions. (3) Paired intervals understate uncertainty because they "
              "resample months around one fixed set of trained models. (4) All four systems "
              "are underdispersive, reproducing about one fifth of observed anomaly "
              "amplitude; for applications sensitive to anomaly magnitude this matters more "
              "than the ranking. (5) Extreme-event CSI at a fixed threshold is confounded "
              "with amplitude, and the ranking reverses once amplitude is equalised. (6) "
              "The conditioning pathway applies a modulation of a few percent of feature "
              "magnitude, so its scope to affect the forecast is intrinsically small.")
    para(doc, "Design and data limitations. (7) The 21 months of 2023-2024 were examined "
              "repeatedly during development and cannot support a confirmatory claim; the "
              "two retrospective origins were likewise examined. (8) Insertion depth and "
              "capacity are not matched: EOF-cat alters the first input convolution while "
              "FiLM adds a branch at five depths and 98,784 parameters, and earlier "
              "exploratory tuning cannot be equalised after the fact. (9) A single global "
              "five-score vector cannot encode location-specific teleconnections, and the "
              "six-month average removes within-window timing. (10) The station-derived "
              "gridded target has uneven sampling, and fractional anomalies amplify error "
              "in dry regions. (11) The archive lacks initialisation metadata, so the "
              "operational forecast lead cannot be verified from these files and the scores "
              "should not be compared with published skill at a stated lead. (12) The input "
              "controls are inference-time perturbations outside the joint training "
              "distribution, not retrained feature-removal experiments.")
    para(doc, "Future perspectives. A confirmatory test of this comparison requires "
              "preregistered architecture, metrics and selection rules together with years "
              "held back from inspection; we did not have such years available. Given the "
              "magnitudes measured here, we suggest that comparisons of postprocessing "
              "architectures report the spread of repeated training as a matter of course, "
              "since differences of the size usually reported in this literature are not "
              "otherwise distinguishable from it. For regional applications, the "
              "underdispersion documented in Section 3.4 appears a more promising target "
              "than additional conditioning complexity: calibrating anomaly amplitude "
              "addresses a defect that is large, systematic and shared by every system "
              "evaluated here.")


def conclusions(doc):
    stats = GAP["mean_test"]
    f14 = HINDCAST["folds"]["2014_2019"]["paired_acc"]["film_minus_baseline"]["mean_diff"]
    f20 = HINDCAST["folds"]["2020_2022"]["paired_acc"]["film_minus_baseline"]["mean_diff"]
    heading(doc, "6 Conclusions")
    para(doc, "We compared raw SEAS5 monthly precipitation over China with three matched "
              "U-Net postprocessors under training-period preprocessing and a physically "
              "reconstructed comparator, and we measured how much of the resulting "
              "differences a single training run can resolve.")
    para(doc, "Supplying five global SST EOF scores through feature-wise linear modulation "
              f"lowers monthly spatial ACC by {abs(stats['mean']):.4f} with a standard error "
              f"of {stats['sem']:.4f} relative to the unconditioned network (five "
              f"retrainings, all negative, p = {stats['p']:.4f}). The conditioning does not "
              "merely fail to add skill in this setting; it carries a small, repeatable "
              "cost. Establishing that required repetition: rerunning the identical "
              f"configuration shifts ensemble ACC by up to {f(FLOOR_ACC, 4)}, and changing "
              f"the random seeds would shift the gap by about {f(RESEED, 4)}, both "
              "comparable to or larger than the effect. The opposite rankings we obtained "
              f"at two retrospective training origins, {f(f14, 4)} and {f(f20, 4)}, span "
              "more than either figure and require no physical explanation.")
    para(doc, "Two verification findings accompany the comparison. All four systems "
              "reproduce only about one fifth of observed monthly anomaly amplitude, and "
              "extreme-event CSI at a fixed threshold is dominated by that amplitude: "
              f"equalising it reverses the ranking from "
              f"{' > '.join(FIGVALS['amplitude']['raw_csi_ranking'])} to "
              f"{' > '.join(FIGVALS['amplitude']['equalised_csi_ranking'])}, placing the "
              "unconditioned baseline first. The conditioning pathway itself transmits SST "
              "phase information faithfully, with channel correlations far above a "
              "permutation control, while modulating features by only a few percent; a "
              "persuasive interpretability analysis can therefore belong to a component "
              "that does not help.")
    para(doc, "For regional precipitation applications the practical implications are that "
              "the choice among these postprocessors is less consequential than their "
              "shared underdispersion, that extreme-event scores should be interpreted "
              "alongside output amplitude, and that a comparison of this kind should report "
              "the spread of repeated training. Independent forecast-observation years, "
              "confirmed lead metadata and preregistered model selection remain necessary "
              "before any general or operational skill claim.")


